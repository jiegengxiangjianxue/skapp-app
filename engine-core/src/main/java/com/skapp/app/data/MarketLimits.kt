package com.skapp.app.data

/**
 * 涨停附近的判定阈值。**两个值语义不同，不可互相替代**：
 *
 * - [LIMIT_UP_PCT]：推荐剔除上限。主板涨幅达到该值即视为涨停附近、不可买入（红线）。
 * - [LIMIT_UP_SCAN_PCT]：涨停扫描下限。站点把 ≥9.5% 记为一字/涨停，用于涨停归因与扫描口径。
 *
 * **两个都不是涨跌停判定口径**。真的判涨停要按板块上限（主板 10%、创业/科创 20%、北交所 30%，
 * ST 另有一套），Python 侧唯一实现在 `scripts/limit_caliber.py`。把这里的 9.6/9.5 当成
 * 「涨停线」会直接判错创业板 12%/18% 这类票。
 *
 * 之所以拆成具名常量：过去这两处都是散落的字面量 9.6 / 9.5，改一处极易改错另一处，
 * 而改错方向恰好是「把涨停票放进推荐」。
 */
object MarketLimits {
    const val LIMIT_UP_PCT = 9.6
    const val LIMIT_UP_SCAN_PCT = 9.5
}
